// 字塊：tiles[{word,x,y,fixed?}]（fixed=刻死推不動）；活書：livingBook{everyN,writes}；即時對手：reactiveBook{everyN,agenda}

// —— 大型負荷關用的 ASCII 佈局工具 ——
// 一格一字元，避免手算座標出錯。字塊用下方字典，刻死（fixed）為預設；小寫 d／F 為「可推動」的得／不得。
// 其餘字元（#、@、.、E/N/K/S/G/B/V/x/H/D/C 等物件）原樣進地圖，由引擎生成。
const TILE_LEGEND = {
  o: '外鄉人', z: '市民', a: '任何人', y: '山羊', w: '物', R: '樹木', c: '生物', i: '圍牆',
  f: '不得', p: '得', J: '即',
  L: '離開', j: '進入', u: '推', t: '吃', b: '搬書', k: '砍伐', h: '持有', '2': '兩格', v: '破壞',
  d: '得', F: '不得',   // 可推動的情態字塊（供玩家湊矛盾／拆法）
};
// 地形字元（原樣進地圖）：~ 河、= 木地板、O 洞穴、^ 火堆、% 聖所；物件 T 樹、X 斧頭、Z 追逐者、W 可破圍牆、D 大門、Y 鑰匙、r 石頭。
const LOOSE_CHARS = new Set(['d', 'F', 'J']);   // 得／不得／即 的可推動版（供玩家湊規則、下定義）
function layout(rows) {
  const map = []; const tiles = [];
  rows.forEach((row, y) => {
    let m = '';
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch in TILE_LEGEND) { tiles.push({ word: TILE_LEGEND[ch], x, y, fixed: !LOOSE_CHARS.has(ch) }); m += '.'; }
      else m += ch;
    }
    map.push(m);
  });
  return { map, tiles };
}

